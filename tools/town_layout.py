def draw_screen(z, polys, scale=14):
    """camera-view composite (images at their real relative scale), back to front"""
    sx = lambda x, zz: x * R[0] + zz * R[1]; sy = lambda x, zz: x * U[0] + zz * U[1]
    W, H = 1500, 950; cx0, cy0 = W / 2, H * 0.55
    im = Image.new("RGBA", (W, H), (96, 140, 80, 255)); d = ImageDraw.Draw(im)
    P = lambda x, zz: (cx0 + sx(x, zz) * scale, cy0 - sy(x, zz) * scale)
    for p in z["patches"]:
        if p["shape"] == "disc":
            pts = [P(p["radius"] * math.cos(t), p["radius"] * math.sin(t)) for t in [i * math.pi / 30 for i in range(60)]]; d.polygon(pts, fill=(190, 180, 160))
        else:
            q = p["pos"]; d.line([P(q[i], q[i + 1]) for i in range(0, len(q), 2)], fill=(200, 160, 110), width=int(p["width"] * scale * 0.7))
    items = []
    for b in z["imageArt"]:
        items.append((sy(*b["pos"]), "art", b))
    for n in z["npcs"]: items.append((sy(*n["pos"]), "npc", n))
    for p in z["props"]:
        if p["type"] in ("tree", "lamp", "bush"): items.append((sy(*p["pos"]), "prop", p))
    for _, kind, o in sorted(items, key=lambda t: -t[0]):
        if kind == "art":
            img = Image.open(f"/home/claude/townart/clean/{o['image']}.png"); k = scale / o["ppm"]
            img = img.resize((max(1, int(img.width * k)), max(1, int(img.height * k))), Image.LANCZOS)
            ax, ay = o["anchor"]; px, py = P(*o["pos"])
            im.alpha_composite(img, (int(px - ax * k), int(py - ay * k)))
        elif kind == "npc":
            px, py = P(*o["pos"]); d.rectangle([px - 4, py - 1.25 * 0.79 * scale, px + 4, py], fill=(255, 230, 0)); d.text((px + 5, py - 14), o["npc"], fill=(0, 0, 0))
        else:
            px, py = P(*o["pos"]); r = 5 if o["type"] == "lamp" else 14
            d.ellipse([px - r, py - 2 * r, px + r, py], fill=(40, 90, 40) if o["type"] != "lamp" else (60, 60, 70))
    im.save(os.path.join(OUT, "town_layout_screen.png"))


if __name__ == "__main__":
    data = json.load(open(ZONES)); town = next(t for t in data["zones"] if t["id"] == "town")
    if "imageArt" in town: pass
    town, polys = build_town(town); draw_screen(town, polys)
