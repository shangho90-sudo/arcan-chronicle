def entrance_world(b, out=0.95):
    """point on the base edge under the door (image x), pushed out of the footprint by `out` metres"""
    ex = b["entrance"][0]; F, L, Rr = b["F"], b["L"], b["R"]
    A = L if ex < F[0] else Rr
    t = (ex - F[0]) / (A[0] - F[0]); py = F[1] + (A[1] - F[1]) * t
    gx, gz = img_to_ground(b, ex, py)
    p = footprint(b); cx = sum(q[0] for q in p) / 4; cz = sum(q[1] for q in p) / 4
    e0 = img_to_ground(b, *F); e1 = img_to_ground(b, *A)
    nx, nz = -(e1[1] - e0[1]), (e1[0] - e0[0]); m = math.hypot(nx, nz); nx, nz = nx / m, nz / m
    if (gx - cx) * nx + (gz - cz) * nz < 0: nx, nz = -nx, -nz
    return gx + nx * out, gz + nz * out


def build_town(z):
    # replace procedural buildings, fountain prop and props that now sit under / inside the new art
    z["buildings"] = []
    polys = {b["id"]: footprint(b) for b in assets}
    def clear_of_art(x, zz, m):
        return all(not inside(p, x, zz) and min(seg_dist(x, zz, p[i], p[i - 1]) for i in range(len(p))) > m for p in polys.values())
    z["bounds"] = BOUNDS
    keep = []
    # boundary: west fence column moves out to the new edge, south row is extended (gate kept), new edge trees
    z["props"] = [p for p in z["props"] if p["type"] != "fence"]
    for x in range(-30, 31, 4):
        if -1 <= x <= 7: continue
        z["props"].append(dict(type="fence", pos=[float(x), -21.0], rot=0.0, scale=1.0, variant="", w=4.0, d=0.0))
    for zz in range(-22, 28, 4):
        z["props"].append(dict(type="fence", pos=[-30.5, float(zz)], rot=90.0, scale=1.0, variant="", w=4.0, d=0.0))
    import random as _r; rnd = _r.Random(11)
    for x in range(-27, 28, 6):
        z["props"].append(dict(type="tree", pos=[x + rnd.uniform(-1, 1), 26.3 + rnd.uniform(-0.6, 0.6)], rot=rnd.uniform(0, 360), scale=round(rnd.uniform(0.9, 1.2), 2), variant=rnd.choice(["leaves", "leaves", "leaves_autumn"]), w=0.0, d=0.0))
    for zz in range(-18, 26, 6):
        z["props"].append(dict(type="tree", pos=[28.2 + rnd.uniform(-0.6, 0.6), zz + rnd.uniform(-1, 1)], rot=rnd.uniform(0, 360), scale=round(rnd.uniform(0.9, 1.2), 2), variant=rnd.choice(["leaves", "leaves", "leaves_autumn"]), w=0.0, d=0.0))
    for zz in range(-16, 26, 7):
        z["props"].append(dict(type="tree", pos=[-28.2 + rnd.uniform(-0.6, 0.6), zz + rnd.uniform(-1, 1)], rot=rnd.uniform(0, 360), scale=round(rnd.uniform(0.9, 1.2), 2), variant="leaves", w=0.0, d=0.0))
    for p in z["props"]:
        if p["type"] in ("fountain", "bench", "lamp", "forge", "anvil", "cauldron", "flowerbed", "easel", "barrel", "crate"):
            continue
        if p["type"] in ("flowers", "bush", "tree", "fence", "wall", "signpost") and not clear_of_art(p["pos"][0], p["pos"][1], 1.6):
            continue
        keep.append(p)
    # lamps on the walkway ring around the fountain, between the routes
    for ang in (70, 160, 205, 250, 340):
        t = math.radians(ang); ex, ez = R, (U[0] / math.hypot(*U), U[1] / math.hypot(*U))
        a, bb = FOUNTAIN["a"] + 2.6, FOUNTAIN["b"] + 2.6
        x = ex[0] * a * math.cos(t) + ez[0] * bb * math.sin(t); zz = ex[1] * a * math.cos(t) + ez[1] * bb * math.sin(t)
        keep.append(dict(type="lamp", pos=[round(x, 2), round(zz, 2)], rot=0.0, scale=1.0, variant="", w=0.0, d=0.0))
    # outdoor painting corner for the artist (no building art supplied for the atelier)
    keep.append(dict(type="easel", pos=[-11.2, -5.4], rot=225.0, scale=1.0, variant="", w=0.0, d=0.0))
    keep.append(dict(type="flowers", pos=[-12.6, -4.2], rot=0.0, scale=1.0, variant="", w=0.0, d=0.0))
    z["props"] = keep
    # NPCs: building owners on their entrance anchors, facing out of the door; others re-homed off the fountain
    npcs = []
    for b in assets[1:]:
        ex, ez = entrance_world(b)
        b["entranceWorld"] = [round(ex, 2), round(ez, 2)]
        npcs.append(dict(npc=b["npc"], pos=[round(ex, 2), round(ez, 2)], rot=round(math.degrees(math.atan2(-0.7071, -0.7071)), 2), building=b["id"]))
    npcs.append(dict(npc="master_artist", pos=[-10.0, -6.6], rot=45.0))
    npcs.append(dict(npc="elder", pos=[-4.6, -8.2], rot=45.0))
    npcs.append(dict(npc="guard", pos=[5.6, -16.6], rot=-18.64))
    z["npcs"] = npcs
    z["spawns"] = [dict(id="start", pos=[-1.0, -10.5], rot=45.0), dict(id="from_field", pos=[3.0, -16.0], rot=0.0), dict(id="revive", pos=[-2.6, -9.6], rot=45.0)]
    z["heights"] = []   # the old atelier terrace is gone
    # ground: cobbled plaza big enough for the fountain + walkway, warm paths to every entrance and the gate
    patches = [dict(tex="cobble", shape="disc", pos=[0, 0], radius=12.6, width=0)]
    for n in npcs:
        if "building" not in n: continue
        x, zz = n["pos"]; d = math.hypot(x, zz); sx, sz = x / d * 11.5, zz / d * 11.5
        patches.append(dict(tex="cobble_warm", shape="path", pos=[round(sx, 2), round(sz, 2), x, zz], radius=0, width=2.6))
