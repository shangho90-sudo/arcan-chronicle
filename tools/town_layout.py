"""Town layout with the painted building / fountain images (web build).

Input : assets/data/zones.json (town as generated by the Unity project's Tools/DataGen/make_zones.py)
        /home/claude/townart/anchors.json  (per-image ground corners measured on the clean images)
Output: assets/data/zones.json (town replaced), tools/out/town_layout_top.png, tools/out/town_layout_screen.png

Each painted asset is a fixed quarter-view image. It is placed by a ground anchor pixel (the front corner
of the building base, or the centre of the fountain's ground ellipse) and a scale in image pixels per
screen-metre (measured from door / barrel heights). The world footprint is recovered from the base corners
in the image with the game camera's projection, so collision, NPC anchors and the drawn picture agree.
"""
import json, math, os, sys
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
ZONES = os.path.join(ROOT, "assets", "data", "zones.json")
ANCH = json.load(open("/home/claude/townart/anchors.json"))
OUT = os.path.join(HERE, "out"); os.makedirs(OUT, exist_ok=True)

PITCH, YAW = math.radians(38), math.radians(45)
R = (math.cos(YAW), -math.sin(YAW))                                   # screen right  (x, z)
U = (math.sin(YAW) * math.sin(PITCH), math.cos(YAW) * math.sin(PITCH))  # screen up from ground motion (x, z)


def img_to_ground(b, px, py):
    """image pixel on the ground plane -> world (x, z) for a placed asset b"""
    ax, ay = b["anchor"]; dsx = (px - ax) / b["ppm"]; dsy = -(py - ay) / b["ppm"]
    det = R[0] * U[1] - R[1] * U[0]
    dx = (dsx * U[1] - R[1] * dsy) / det; dz = (R[0] * dsy - dsx * U[0]) / det
    return (b["pos"][0] + dx, b["pos"][1] + dz)


def footprint(b, inset=0.0):
    if b["kind"] == "ellipse":
        cx, cz = b["pos"]; a, bb = b["a"] - inset, b["b"] - inset
        ex, ez = R, (U[0] / math.hypot(*U), U[1] / math.hypot(*U))
        return [(cx + ex[0] * a * math.cos(t) + ez[0] * bb * math.sin(t), cz + ex[1] * a * math.cos(t) + ez[1] * bb * math.sin(t))
                for t in [i * 2 * math.pi / 40 for i in range(40)]]
    F = img_to_ground(b, *b["F"]); L = img_to_ground(b, *b["L"]); Rr = img_to_ground(b, *b["R"])
    B = (L[0] + Rr[0] - F[0], L[1] + Rr[1] - F[1])
    pts = [F, Rr, B, L]
    if inset:
        cx = sum(p[0] for p in pts) / 4; cz = sum(p[1] for p in pts) / 4
        pts = [(p[0] + (cx - p[0]) * inset / math.hypot(cx - p[0], cz - p[1]), p[1] + (cz - p[1]) * inset / math.hypot(cx - p[0], cz - p[1])) for p in pts]
    return pts


def seg_dist(px, pz, a, b):
    vx, vz = b[0] - a[0], b[1] - a[1]; t = max(0, min(1, ((px - a[0]) * vx + (pz - a[1]) * vz) / (vx * vx + vz * vz)))
    return math.hypot(px - a[0] - vx * t, pz - a[1] - vz * t)


def inside(poly, x, z):
    c = False
    for i in range(len(poly)):
        a, b = poly[i], poly[i - 1]
        if (a[1] > z) != (b[1] > z) and x < (b[0] - a[0]) * (z - a[1]) / (b[1] - a[1]) + a[0]: c = not c
    return c


def poly_dist(p1, p2):
    if any(inside(p2, *q) for q in p1) or any(inside(p1, *q) for q in p2): return 0.0
    return min(min(seg_dist(q[0], q[1], p2[i], p2[i - 1]) for i in range(len(p2))) for q in p1)


